        /// <summary>
        /// The statements of a C# member that calls <paramref name="e"/> with <paramref name="arguments"/> (C# expressions,
        /// in the export's order; <c>self</c> included), and gives its result when <paramref name="returns"/>.
        /// </summary>
        private void Call(StringBuilder t, string indent, CExport e, IReadOnlyList<string> arguments, bool returns)
        {
            var prep = new List<string>();
            var pins = new List<string>();
            var after = new List<string>();
            var native = new List<string>();
            for (int i = 0; i < e.Arguments.Count; i++)
            {
                var x = e.Arguments[i].Cross;
                string a = arguments[i];
                string n = "__a" + i;
                switch (x.Kind)
                {
                    case CrossKind.Number:
                        native.Add(PrimitiveOf(x) == Primitive.Bool ? $"({a} ? (byte)1 : (byte)0)" : a);
                        break;
                    case CrossKind.Enum or CrossKind.Pointer:
                        native.Add(a);
                        break;
                    case CrossKind.Text:
                        if (!x.Nullable)
                            prep.Add($"global::System.ArgumentNullException.ThrowIfNull({a});");
                        prep.Add($"int {n}_max = {a} is null ? 0 : global::System.Text.Encoding.UTF8.GetMaxByteCount({a}.Length);");
                        prep.Add($"global::System.Span<byte> {n}_buffer = {n}_max <= 512 ? stackalloc byte[512] : new byte[{n}_max];");
                        prep.Add($"int {n}_length = {a} is null ? 0 : global::System.Text.Encoding.UTF8.GetBytes({a}, {n}_buffer);");
                        pins.Add($"byte* {n} = {a} is null ? default(global::System.Span<byte>) : {n}_buffer");
                        native.Add(n);
                        native.Add($"(nuint){n}_length");
                        break;
                    case CrossKind.Value:
                        prep.Add($"{Full(x.Target!)} {n} = {a};");
                        native.Add("&" + n);
                        break;
                    case CrossKind.Optional:
                        prep.Add($"{Public(x.Element!)} {n} = {a}.GetValueOrDefault();");
                        native.Add($"{a}.HasValue ? &{n} : null");
                        break;
                    case CrossKind.Array:
                        pins.Add($"{Element(x.Element!)}* {n} = {a}");
                        native.Add(n);
                        native.Add($"(nuint){a}.Length");
                        break;
                    case CrossKind.Function:
                        if (!x.Nullable)
                            prep.Add($"global::System.ArgumentNullException.ThrowIfNull({a});");
                        native.Add($"{a} is null ? null : &global::{root}.LarvaCallback{x.Callback!.Index}.Invoke");
                        native.Add($"{a} is null ? null : global::{root}.LarvaCallbacks.Context({a})");
                        native.Add($"{a} is null ? null : &global::{root}.LarvaCallbacks.Release");
                        break;
                    case CrossKind.List when a == "this":
                        native.Add("this.__Handle");
                        after.Add("global::System.GC.KeepAlive(this);");
                        break;
                    case CrossKind.List:
                    {
                        string list = ListFull(x.List!);
                        if (!x.Nullable)
                            prep.Add($"global::System.ArgumentNullException.ThrowIfNull({a});");
                        prep.Add($"{list} {n} = {a} as {list} ?? {list}.Copy({a});");
                        native.Add($"{n}.__Handle");
                        after.Add($"if (!ReferenceEquals({n}, {a})) {n}.Dispose(); else global::System.GC.KeepAlive({n});");
                        break;
                    }
                    case CrossKind.Handle when x.Target is { Source.IsInterface: true } target && api.Foreigns.FirstOrDefault(f => f.Interface == target) is { } foreign && a != "this":
                    {
                        if (!x.Nullable)
                            prep.Add($"global::System.ArgumentNullException.ThrowIfNull({a});");
                        prep.Add($"ulong {n} = {a} is null ? 0 : {a} is global::{root}.LarvaObject {n}_own ? {n}_own.__Handle : global::{root}.LarvaForeign{foreign.Index}.Make({a});");
                        native.Add(n);
                        after.Add($"if ({a} is not null and not global::{root}.LarvaObject) {Native}.{api.Prefix}_release({n}); else global::System.GC.KeepAlive({a});");
                        break;
                    }
                    default:
                        if (a == "this")
                        {
                            native.Add("this.__Handle");
                            after.Add("global::System.GC.KeepAlive(this);");
                        }
                        else
                        {
                            if (!x.Nullable)
                                prep.Add($"global::System.ArgumentNullException.ThrowIfNull({a});");
                            native.Add($"{Native}.Handle({a}, nameof({a}))");
                            after.Add($"global::System.GC.KeepAlive({a});");
                        }
                        break;
                }
            }
            string resultType = NativeResult(e);
            switch (e.Returns?.Kind)
            {
                case CrossKind.Value:
                    prep.Add($"{Full(e.Returns.Target!)} __result;");
                    native.Add("&__result");
                    break;
                case CrossKind.Array:
                    prep.Add("nuint __count = 0;");
                    native.Add("&__count");
                    break;
                case CrossKind.Optional:
                    prep.Add($"{Public(e.Returns.Element!)} __result;");
                    native.Add("&__result");
                    break;
            }
            prep.Add("ulong __error = 0;");
            native.Add("&__error");
            if (resultType != "void")
                prep.Add($"{resultType} __r;");
            foreach (var line in prep)
                t.Append(indent).Append(line).Append('\n');
            string inner = indent;
            foreach (var pin in pins)
            {
                t.Append(inner).Append($"fixed ({pin})\n");
            }
            string call = $"{Native}.{e.Name}({string.Join(", ", native)});";
            t.Append(pins.Count > 0 ? inner + "    " : inner).Append(resultType != "void" ? "__r = " + call : call).Append('\n');
            foreach (var line in after)
                t.Append(indent).Append(line).Append('\n');
            t.Append(indent).Append($"if (__error != 0)\n{indent}    throw {Native}.Error(__error);\n");
            if (!returns || e.Returns is null)
                return;
            t.Append(indent).Append("return ").Append(Convert(e.Returns)).Append(";\n");
        }

        /// <summary>The C# value of a call's result (in <c>__r</c>, <c>__result</c>, <c>__count</c>).</summary>
        private string Convert(Cross x) => x.Kind switch
        {
            CrossKind.Number => PrimitiveOf(x) == Primitive.Bool ? "__r != 0" : "__r",
            CrossKind.Enum or CrossKind.Pointer => "__r",
            CrossKind.Text => x.Nullable ? $"{Native}.Text(__r)" : $"{Native}.Text(__r) ?? \"\"",
            CrossKind.Value => "__result",
            CrossKind.Optional => $"__r != 0 ? __result : null",
            CrossKind.Array => $"__TakeArray(__r, __count)",
            CrossKind.List => x.Nullable ? $"__r == 0 ? null : new {ListFull(x.List!)}(__r)" : $"new {ListFull(x.List!)}(__r)",
            _ => x.Nullable ? $"__r == 0 ? null : {Wrap(x.Target!)}" : Wrap(x.Target!),
        };

        /// <summary>
        /// The C# object for a handle <c>__r</c> of <paramref name="type"/>: the class itself when no class C# sees derives
        /// from it, else the class the object is (asked to the library), and what the library gives of an interface that is
        /// not one of those classes, a proxy.
        /// </summary>
        private string Wrap(PolyglotType type)
        {
            bool Derives(PolyglotType c)
            {
                for (var b = c.Source.Base; b is not null; b = b.Base)
                    if (b == type.Source)
                        return true;
                return false;
            }
            string proxy = $"{Full(type)[..^type.Names[CS].Length]}{Proxy(type)}";
            if (type.Source.IsInterface)
                return $"{Native}.Wrap<{Full(type)}>(__r, static h => {Native}.Foreign(h) as {Full(type)} ?? new {proxy}(h))";
            if (!api.Classes.Any(Derives))
                return $"new {Full(type)}(__r)";
            return $"{Native}.Wrap<{Full(type)}>(__r, static h => new {Full(type)}(h))";
        }

