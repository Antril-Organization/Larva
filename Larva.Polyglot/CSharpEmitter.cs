        private void Run(string version)
        {
            text.Append($"// {model.Assembly.Name} {version}: generated by larva polyglot. Do not edit.\n");
            text.Append("#nullable enable\n#pragma warning disable CS1591, CS8500\n\n");
            NativeClass();
            Lists();
            Exceptions();
            Callbacks();
            Foreigns();
            foreach (var group in model.Types.GroupBy(t => t.Namespaces[CS]))
            {
                text.Append($"namespace {group.Key}\n{{\n");
                foreach (var type in group.Where(t => t.Owner is null))
                    Type(type, "    ");
                text.Append("}\n\n");
            }
            text.Append($$"""
                namespace {{root}}
                {
                    internal static unsafe class LarvaArrays
                    {
                        /// <summary>An array result: the library's block copied into a C# array, the block freed.</summary>
                        internal static T[] Take<T>(T* block, nuint count) where T : unmanaged
                        {
                            var made = new global::System.ReadOnlySpan<T>(block, checked((int)count)).ToArray();
                            LarvaNative.{{api.Prefix}}_free(block);
                            return made;
                        }
                    }
                }

                """);
            text.Replace("__TakeArray(", $"global::{root}.LarvaArrays.Take(");
        }

        private bool Offered(PolyglotType type) => type.Source.Arity == 0 && (
            api.Handles.Any(h => h.Name == type.Names[TargetLanguage.C]) || api.Structs.Any(s => s.Name == type.Names[TargetLanguage.C])
            || api.Enums.Any(e => e.Name == type.Names[TargetLanguage.C]) || type.IsModule || type.Source.IsStatic);

        private void Type(PolyglotType type, string indent)
        {
            if (!Offered(type))
                return;
            var source = type.Source;
            string name = type.Names[CS];
            if (source.IsEnum)
            {
                Enum(type, indent);
                return;
            }
            if (type.IsModule && type.Members.All(m => !byMember.ContainsKey(m) && m.Kind != NameKind.Constant))
                return;
            Doc(source.Doc, indent);
            if (type.IsModule || source.IsStatic)
            {
                text.Append($"{indent}public static unsafe class {name}\n{indent}{{\n");
                Members(type, indent + "    ", self: null);
                text.Append($"{indent}}}\n\n");
                return;
            }
            if (source.IsValue)
            {
                Struct(type, indent);
                return;
            }
            if (source.IsInterface)
            {
                Interface(type, indent);
                return;
            }
            // A class: a handle; its base the base class C# sees (or LarvaObject); the interfaces C# sees that it declares.
            string @base = source.Base is { } b && model.Types.FirstOrDefault(t => t.Source == b) is { } baseType && Offered(baseType)
                ? Full(baseType) : $"global::{root}.LarvaObject";
            var interfaces = Interfaces(type);
            text.Append($"{indent}public unsafe class {name} : {string.Join(", ", [@base, .. interfaces.Select(Full)])}\n{indent}{{\n");
            text.Append($"{indent}    internal {name}(ulong handle) : base(handle) {{ }}\n\n");
            if (api.Exports.FirstOrDefault(e => e.Role == ExportRole.Constructor && e.Owner == type) is { } implicitNew)
            {
                text.Append($"{indent}    public {name}() : base(__New()) {{ }}\n\n");
                text.Append($"{indent}    private static ulong __New()\n{indent}    {{\n");
                Call(text, indent + "        ", implicitNew, [], returns: false);
                text.Append($"{indent}        return __r;\n{indent}    }}\n\n");
            }
            Members(type, indent + "    ", self: "this");
            foreach (var implemented in Closure(interfaces))
                Implementation(implemented, indent + "    ");
            text.Append($"{indent}}}\n\n");
        }

        private void Enum(PolyglotType type, string indent)
        {
            var underlying = type.Source.Definition.Underlying is PrimitiveType u ? Keyword(u.Kind) : "int";
            Doc(type.Source.Doc, indent);
            if (type.Source.Definition.Kind == TypeKind.Bitflags)
                text.Append($"{indent}[global::System.Flags]\n");
            text.Append($"{indent}public enum {type.Names[CS]} : {underlying}\n{indent}{{\n");
            foreach (var member in type.Members.Where(m => m.Kind == NameKind.EnumMember))
            {
                var value = member.Source.Field?.Value switch
                {
                    IntegerConstant i => i.Value,
                    EnumConstant e => e.Value,
                    _ => 0,
                };
                Doc(member.Source.Doc, indent + "    ");
                text.Append($"{indent}    {member.Names[CS][0]} = {value},\n");
            }
            text.Append($"{indent}}}\n\n");
        }

        private void Struct(PolyglotType type, string indent)
        {
            string name = type.Names[CS];
            var described = api.Structs.FirstOrDefault(s => s.Type == type.Source);
            string layout = described is { Union: true } ? "Explicit" : "Sequential";
            string options = (described?.Pack > 0 ? $", Pack = {described.Pack}" : "") + (described?.Size > 0 ? $", Size = {described.Size}" : "");
            text.Append($"{indent}[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.{layout}{options})]\n");
            text.Append($"{indent}public unsafe partial struct {name}\n{indent}{{\n");
            string offset = described is { Union: true } ? "[global::System.Runtime.InteropServices.FieldOffset(0)] " : "";
            // Every instance field, in order (the layout is C's): the public ones by their names, the others hidden.
            var named = type.Members.Where(m => m.Kind == NameKind.Field && !m.Source.IsStatic).ToDictionary(m => m.Source.Field!);
            foreach (var field in type.Source.Definition.Fields.Where(f => (f.Flags & (FieldFlags.Static | FieldFlags.Const)) == 0))
            {
                var global = type.Source.Global(field.Type);
                string fieldName = named.TryGetValue(field, out var member) ? member.Names[CS][0] : "_" + Naming.Shape(field.Name, NameStyle.Camel);
                string access = member is null ? "private" : "public";
                if (member is not null)
                    Doc(member.Source.Doc, indent + "    ");
                // A fixed array of numbers is a fixed buffer.
                if (global is InlineArrayType { Element: PrimitiveType element } array)
                    text.Append($"{indent}    {offset}{access} fixed {Keyword(element.Kind)} {fieldName}[{array.Count}];\n");
                else
                    text.Append($"{indent}    {offset}{access} {FieldType(global)} {fieldName};\n");
            }
            text.Append('\n');
            Members(type, indent + "    ", self: "this", value: true);
            text.Append($"{indent}}}\n\n");
        }

        /// <summary>A struct field's C# type: a number, an enum, another struct.</summary>
        private string FieldType(HirType type) => type switch
        {
            PrimitiveType p => Keyword(p.Kind),
            PointerType { Target: PrimitiveType p } => (p.Kind == Primitive.Void ? "void" : Keyword(p.Kind)) + "*",
            PointerType { Target: NamedType n } when model.Types.FirstOrDefault(t => t.Source == model.Assembly.Catalog.TypeOf(n)) is { Source.IsValue: true } s
                && api.Structs.Any(x => x.Type == s.Source) => Full(s) + "*",
            PointerType or NativeFuncType => "void*",
            NamedType n when model.Types.FirstOrDefault(t => t.Source == model.Assembly.Catalog.TypeOf(n)) is { } t => Full(t),
            _ => "byte",
        };

        /// <summary>The interfaces a type declares that C# sees.</summary>
        private List<PolyglotType> Interfaces(PolyglotType type) =>
            [.. type.Source.Interfaces.Select(i => model.Types.FirstOrDefault(t => t.Source == i)).OfType<PolyglotType>().Where(Offered)];

        /// <summary>Interfaces and every interface they extend (that C# sees), once each.</summary>
        private List<PolyglotType> Closure(IEnumerable<PolyglotType> interfaces)
        {
            var all = new List<PolyglotType>();
            void Add(PolyglotType i)
            {
                if (all.Contains(i))
                    return;
                all.Add(i);
                foreach (var b in Interfaces(i))
                    Add(b);
            }
            foreach (var i in interfaces)
                Add(i);
            return all;
        }

        /// <summary>
        /// An interface's members implemented explicitly (<c>IReader.ReadNext()</c>): each calls the interface's own
        /// function, which the library dispatches to the object's class.
        /// </summary>
        private void Implementation(PolyglotType iface, string indent)
        {
            string owner = Full(iface);
            foreach (var member in iface.Members)
            {
                if (!byMember.TryGetValue(member, out var exports) || member.Source.IsStatic)
                    continue;
                string name = member.Names[CS][0];
                if (member.Kind == NameKind.Method && exports.FirstOrDefault(e => e.Role == ExportRole.Method) is { } m)
                {
                    text.Append($"{indent}{ReturnType(m)} {owner}.{name}({Parameters(m, skipSelf: true)})\n{indent}{{\n");
                    Call(text, indent + "    ", m, Arguments(m, "this"), returns: true);
                    text.Append($"{indent}}}\n\n");
                }
                else if (member.Kind == NameKind.Property && exports.FirstOrDefault(e => e.Role == ExportRole.Getter) is { } g)
                {
                    text.Append($"{indent}{Public(g.Returns!)} {owner}.{name}\n{indent}{{\n{indent}    get\n{indent}    {{\n");
                    Call(text, indent + "        ", g, Arguments(g, "this"), returns: true);
                    text.Append($"{indent}    }}\n");
                    if (exports.FirstOrDefault(e => e.Role == ExportRole.Setter) is { } s)
                    {
                        text.Append($"{indent}    set\n{indent}    {{\n");
                        Call(text, indent + "        ", s, Arguments(s, "this"), returns: false);
                        text.Append($"{indent}    }}\n");
                    }
                    text.Append($"{indent}}}\n\n");
                }
            }
        }

        private void Interface(PolyglotType type, string indent)
        {
            string name = type.Names[CS];
            var bases = Interfaces(type);
            text.Append($"{indent}public unsafe interface {name}{(bases.Count > 0 ? " : " + string.Join(", ", bases.Select(Full)) : "")}\n{indent}{{\n");
            foreach (var member in type.Members)
            {
                if (!byMember.TryGetValue(member, out var exports) || member.Source.IsStatic)
                    continue;
                Doc(member.Source.Doc, indent + "    ");
                if (member.Kind == NameKind.Method && exports.FirstOrDefault(e => e.Role == ExportRole.Method) is { } m)
                    text.Append($"{indent}    {ReturnType(m)} {member.Names[CS][0]}({Parameters(m, skipSelf: true)});\n");
                else if (member.Kind is NameKind.Property && exports.FirstOrDefault(e => e.Role == ExportRole.Getter) is { } g)
                    text.Append($"{indent}    {Public(g.Returns!)} {member.Names[CS][0]} {{ get;{(exports.Any(e => e.Role == ExportRole.Setter) ? " set;" : "")} }}\n");
            }
            text.Append($"{indent}}}\n\n");
            // What the library gives of the interface: a handle that implements it.
            text.Append($"{indent}internal sealed unsafe class {Proxy(type)} : global::{root}.LarvaObject, {name}\n{indent}{{\n");
            text.Append($"{indent}    internal {Proxy(type)}(ulong handle) : base(handle) {{ }}\n\n");
            foreach (var implemented in Closure([type]))
                Implementation(implemented, indent + "    ");
            text.Append($"{indent}}}\n\n");
        }

        private string ReturnType(CExport e) => e.Role == ExportRole.Constructor ? "" : e.Returns is { } r ? Public(r) : "void";

        /// <summary>A member's C# parameters (from the export's arguments; without self).</summary>
        private string Parameters(CExport e, bool skipSelf)
        {
            var member = e.Member!;
            var names = member.Parameters[CS];
            var list = new List<string>();
            int p = 0;
            foreach (var (argument, x) in e.Arguments)
            {
                if (argument == "self")
                {
                    if (!skipSelf)
                        list.Add($"{Public(x)} self");
                    continue;
                }
                if (argument == "value" && e.Role == ExportRole.Setter)
                    continue;
                list.Add($"{Public(x, parameter: true)} {names[p++]}");
            }
            return string.Join(", ", list);
        }

        private IReadOnlyList<string> Arguments(CExport e, string? self)
        {
            var member = e.Member!;
            var names = member.Parameters[CS];
            var list = new List<string>();
            int p = 0;
            foreach (var (argument, _) in e.Arguments)
            {
                if (argument == "self")
                    list.Add(self ?? "self");
                else if (argument == "value" && e.Role == ExportRole.Setter)
                    list.Add("value");
                else
                    list.Add(names[p++]);
            }
            return list;
        }

        /// <summary>The members of a type (or a module) that C offers, as C# members.</summary>
        private void Members(PolyglotType type, string indent, string? self, bool value = false, bool instanceOnly = false)
        {
            int helpers = 0;
            foreach (var member in type.Members)
            {
                if (member.Kind == NameKind.Constant && !instanceOnly)
                {
                    Constant(member, indent);
                    continue;
                }
                if (!byMember.TryGetValue(member, out var exports))
                    continue;
                if (instanceOnly && member.Source.IsStatic)
                    continue;
                string name = member.Names[CS][0];
                string modifiers = member.Source.IsStatic ? "public static" : "public";
                // What C# objects already have: ToString() overrides object's; Dispose() LarvaObject's (and then gives the
                // handle back); a member a base class C# sees has too is `new`.
                var first = exports[0];
                bool noParameters = first.Arguments.All(a => a.Name == "self");
                bool toString = member.Kind == NameKind.Method && !member.Source.IsStatic && name == "ToString" && noParameters && first.Returns?.Kind == CrossKind.Text;
                bool hash = member.Kind == NameKind.Method && !member.Source.IsStatic && name == "GetHashCode" && noParameters
                    && first.Returns is { Kind: CrossKind.Number } h && PrimitiveOf(h) == Primitive.I32;
                bool dispose = member.Kind == NameKind.Method && !member.Source.IsStatic && !value && name == "Dispose" && noParameters && first.Returns is null && !type.Source.IsInterface;
                if (toString || dispose || hash)
                    modifiers = "public override";
                else if (!member.Source.IsStatic && Hides(type, name, Signature(member, first)))
                {
                    // An override of what a base class already has, alike in C#: the base's member calls the library,
                    // which picks this one (its methods are virtual there), so it is not said again.
                    if (Overrides(member) && Inherited(type, name, Signature(member, first)) is { } inherited
                        && byMember[inherited][0].Returns?.C == first.Returns?.C && byMember[inherited].Count == exports.Count)
                        continue;
                    modifiers = "public new";
                }
                switch (member.Kind)
                {
                    case NameKind.Constructor:
                    {
                        var e = exports[0];
                        Doc(member.Source.Doc, indent);
                        if (value)
                        {
                            // A struct's constructor: the library writes the value.
                            text.Append($"{indent}public {type.Names[CS]}({Parameters(e, skipSelf: true)})\n{indent}{{\n");
                            Call(text, indent + "    ", e, Arguments(e, null), returns: false);
                            text.Append($"{indent}    this = __result;\n{indent}}}\n\n");
                        }
                        else
                        {
                            // A class's constructor: the handle comes from a static function (C# runs base(...) first).
                            string make = $"__New{helpers++}";
                            text.Append($"{indent}public {type.Names[CS]}({Parameters(e, skipSelf: true)}) : base({make}({string.Join(", ", member.Parameters[CS])})) {{ }}\n\n");
                            text.Append($"{indent}private static ulong {make}({Parameters(e, skipSelf: true)})\n{indent}{{\n");
                            Call(text, indent + "    ", e, Arguments(e, null), returns: false);
                            text.Append($"{indent}    return __r;\n{indent}}}\n\n");
                        }
                        break;
                    }
                    case NameKind.Method:
                    {
                        var e = exports[0];
                        Doc(member.Source.Doc, indent);
                        string selfExpression = value ? "this" : self ?? "this";
                        text.Append($"{indent}{modifiers} {(toString ? "string" : ReturnType(e))} {name}({Parameters(e, skipSelf: true)})\n{indent}{{\n");
                        Call(text, indent + "    ", e, Arguments(e, selfExpression), returns: true);
                        if (dispose)
                            text.Append($"{indent}    base.Dispose();\n");
                        text.Append($"{indent}}}\n\n");
                        break;
                    }
                    case NameKind.Property or NameKind.Field:
                    {
                        var getter = exports.FirstOrDefault(x => x.Role == ExportRole.Getter);
                        var setter = exports.FirstOrDefault(x => x.Role == ExportRole.Setter);
                        if (getter is null && setter is null)
                            break;
                        var x = (getter?.Returns ?? setter!.Arguments[^1].Cross);
                        Doc(member.Source.Doc, indent);
                        text.Append($"{indent}{modifiers} {Public(x)} {name}\n{indent}{{\n");
                        if (getter is not null)
                        {
                            text.Append($"{indent}    get\n{indent}    {{\n");
                            Call(text, indent + "        ", getter, Arguments(getter, "this"), returns: true);
                            text.Append($"{indent}    }}\n");
                        }
                        if (setter is not null)
                        {
                            text.Append($"{indent}    set\n{indent}    {{\n");
                            Call(text, indent + "        ", setter, Arguments(setter, "this"), returns: false);
                            text.Append($"{indent}    }}\n");
                        }
                        text.Append($"{indent}}}\n\n");
                        break;
                    }
                }
            }
        }

        /// <summary>What hides what in C#: a method's parameter types (null for properties and fields, which hide by name).</summary>
        private string? Signature(PolyglotMember member, CExport export) =>
            member.Kind == NameKind.Method ? string.Join(",", export.Arguments.Where(a => a.Name != "self").Select(a => Public(a.Cross, parameter: true))) : null;

        /// <summary>Whether a base class C# sees has a member that this one hides (the same name, and parameters for methods).</summary>
        private bool Hides(PolyglotType type, string name, string? signature) =>
            signature is "" && name == "Dispose" && !type.Source.IsValue // LarvaObject's
            || Inherited(type, name, signature) is not null;

        /// <summary>The member of a base class C# sees that one named <paramref name="name"/> (with these parameters, for a method) hides.</summary>
        private PolyglotMember? Inherited(PolyglotType type, string name, string? signature)
        {
            for (var b = type.Source.Base; b is not null; b = b.Base)
            {
                if (model.Types.FirstOrDefault(t => t.Source == b) is not { } baseType || !Offered(baseType))
                    break;
                foreach (var m in baseType.Members)
                {
                    if (!byMember.TryGetValue(m, out var exports) || m.Names[CS] is not [var n, ..] || n != name || m.Source.IsStatic)
                        continue;
                    if (m.Kind is NameKind.Method == signature is not null && (signature is null || Signature(m, exports[0]) == signature))
                        return m;
                }
            }
            return null;
        }

        /// <summary>Whether the library's member overrides a virtual one (a method, or a property's accessors).</summary>
        private static bool Overrides(PolyglotMember member) =>
            member.Source.Method is { } method ? (method.Flags & MethodFlags.Override) != 0
            : member.Source.Property is { } property && (property.Flags & MemberFlags.Override) != 0;

        private void Constant(PolyglotMember member, string indent)
        {
            string? literal = member.Source.Field?.Value switch
            {
                IntegerConstant i => i.Value.ToString(),
                BoolConstant b => b.Value ? "true" : "false",
                StringConstant s => "\"" + s.Value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\"",
                _ => null,
            };
            string? type = member.Source.ValueType switch
            {
                PrimitiveType p when p.Kind is not (Primitive.Void or Primitive.Char) && Keyword(p.Kind) != "void" => Keyword(p.Kind),
                NamedType n when member.Owner.Source.Catalog.TypeOf(n) is { FullName: "System.String" } => "string",
                _ => null,
            };
            if (literal is null || type is null || type == "string" && member.Source.Field?.Value is not StringConstant)
                return;
            Doc(member.Source.Doc, indent);
            text.Append($"{indent}public const {type} {member.Names[CS][0]} = {literal};\n\n");
        }

        /// <summary>Each list type: a class that is an <see cref="IList{T}"/> over the library's list.</summary>
        private void Lists()
        {
            if (byList.Count == 0)
                return;
            text.Append($"namespace {root}\n{{\n");
            foreach (var (_, exports) in byList)
            {
                var list = exports[0].List!;
                string name = ListClass(list);
                string item = Public(list.Element);
                CExport Op(ExportRole role) => exports.First(e => e.Role == role);
                text.Append($"    /// <summary>A list of the library's (not a copy): reading and writing it reads and writes the library's.</summary>\n");
                text.Append($"    public sealed unsafe class {name} : global::{root}.LarvaObject, global::System.Collections.Generic.IList<{item}>\n    {{\n");
                text.Append($"        internal {name}(ulong handle) : base(handle) {{ }}\n\n");
                text.Append($"        public {name}() : base(__New()) {{ }}\n\n");
                text.Append("        private static ulong __New()\n        {\n");
                Call(text, "            ", Op(ExportRole.ListNew), [], returns: false);
                text.Append("            return __r;\n        }\n\n");
                text.Append("        /// <summary>A new list of the library's with the items of <paramref name=\"items\"/>.</summary>\n");
                text.Append($"        public static {name} Copy(global::System.Collections.Generic.IEnumerable<{item}> items)\n        {{\n");
                text.Append($"            var made = new {name}();\n            foreach (var item in items)\n                made.Add(item);\n            return made;\n        }}\n\n");
                text.Append("        public int Count\n        {\n            get\n            {\n");
                Call(text, "                ", Op(ExportRole.ListCount), ["this"], returns: true);
                text.Append("            }\n        }\n\n");
                text.Append($"        public {item} this[int index]\n        {{\n            get\n            {{\n");
                Call(text, "                ", Op(ExportRole.ListGet), ["this", "index"], returns: true);
                text.Append("            }\n            set\n            {\n");
