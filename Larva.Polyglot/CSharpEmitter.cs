        private void Doc(string? doc, string indent)
        {
            if (doc is not { Length: > 0 })
                return;
            text.Append(indent).Append("/// <summary>\n");
            foreach (var line in doc.Split('\n'))
                text.Append(indent).Append("/// ").Append(line.TrimEnd().Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")).Append('\n');
            text.Append(indent).Append("/// </summary>\n");
        }
