        /// <summary>The C# parameters of an export's C function: blittable types only.</summary>
        private IEnumerable<string> NativeParameters(CExport e)
        {
            if (e.Role == ExportRole.ForeignNew)
            {
                var foreign = api.Foreigns.First(f => f.Function == e.Name);
                for (int m = 0; m < foreign.Methods.Count; m++)
                    yield return $"{Pointer(foreign.Methods[m].Fn)} f{m}";
                yield return "void* context";
                yield return "delegate* unmanaged<void*, void> release";
                yield return "ulong* error";
                yield break;
            }
            if (e.Role is ExportRole.Release or ExportRole.Free or ExportRole.StringFree or ExportRole.ErrorMessage or ExportRole.ThreadDetach or ExportRole.ErrorType or ExportRole.TypeOf or ExportRole.CallbackError or ExportRole.ForeignContext or ExportRole.StringNew)
            {
                // The library's helpers: their C parameters as they are.
                foreach (var parameter in e.Parameters)
                    yield return (parameter.Type switch
                    {
                        "void *" => "void*",
                        "char *" or "const char *" => "byte*",
                        "size_t" => "nuint",
                        var pointer when pointer.EndsWith('*') => "ulong*",
                        _ => "ulong",
                    }) + " " + parameter.Name;
                yield break;
            }
            int i = 0;
            foreach (var (_, x) in e.Arguments)
            {
                string n = "a" + i++;
                switch (x.Kind)
                {
                    case CrossKind.Number:
                        yield return $"{(PrimitiveOf(x) == Primitive.Bool ? "byte" : Keyword(PrimitiveOf(x)))} {n}";
                        break;
                    case CrossKind.Enum:
                        yield return $"{Full(x.Target!)} {n}";
                        break;
                    case CrossKind.Text:
                        yield return $"byte* {n}";
                        yield return $"nuint {n}_length";
                        break;
                    case CrossKind.Value:
                        yield return $"{Full(x.Target!)}* {n}";
                        break;
                    case CrossKind.Array:
                        yield return $"{Element(x.Element!)}* {n}";
                        yield return $"nuint {n}_count";
                        break;
                    case CrossKind.Optional:
                        yield return $"{Element(x.Element!)}* {n}";
                        break;
                    case CrossKind.Pointer:
                        yield return $"{Pointer(x)} {n}";
                        break;
                    case CrossKind.Function:
                        yield return $"{Pointer(x.Callback!)} {n}";
                        yield return $"void* {n}_context";
                        yield return $"delegate* unmanaged<void*, void> {n}_release";
                        break;
                    default:
                        yield return $"ulong {n}";
                        break;
                }
            }
            switch (e.Returns?.Kind)
            {
                case CrossKind.Value:
                    yield return $"{Full(e.Returns.Target!)}* result";
                    break;
                case CrossKind.Array:
                    yield return "nuint* result_count";
                    break;
                case CrossKind.Optional:
                    yield return $"{Element(e.Returns.Element!)}* result";
                    break;
            }
            if (e.Role is not (ExportRole.Release or ExportRole.Free or ExportRole.StringFree or ExportRole.ErrorMessage or ExportRole.ThreadDetach or ExportRole.ErrorType or ExportRole.TypeOf or ExportRole.CallbackError or ExportRole.ForeignContext or ExportRole.StringNew))
                yield return "ulong* error";
        }

        private string NativeResult(CExport e) => e.Role switch
        {
            ExportRole.ErrorMessage or ExportRole.ErrorType => "byte*",
            ExportRole.TypeOf => "int",
            ExportRole.ForeignContext => "void*",
            ExportRole.StringNew => "ulong",
            _ => NativeReturns(e),
        };

        private string NativeReturns(CExport e) => e.Returns switch
        {
            null => "void",
            { Kind: CrossKind.Number } x => PrimitiveOf(x) == Primitive.Bool ? "byte" : Keyword(PrimitiveOf(x)),
            { Kind: CrossKind.Enum } x => Full(x.Target!),
            { Kind: CrossKind.Text } => "byte*",
            { Kind: CrossKind.Value } => "void",
            { Kind: CrossKind.Array } x => Element(x.Element!) + "*",
            { Kind: CrossKind.Optional } => "byte",
            { Kind: CrossKind.Pointer } x => Pointer(x),
            _ => "ulong",
        };

        /// <summary>The exception .NET has for each of System.Core's: its type and how it is made from a message.</summary>
        private static readonly Dictionary<string, (string Type, string Arguments)> Known = new(StringComparer.Ordinal)
        {
            ["System.ArgumentError"] = ("global::System.ArgumentException", "message, inner"),
            ["System.ArgumentOutOfRangeError"] = ("global::System.ArgumentOutOfRangeException", "message, inner"),
            ["System.IndexError"] = ("global::System.IndexOutOfRangeException", "message, inner"),
            ["System.KeyNotFoundError"] = ("global::System.Collections.Generic.KeyNotFoundException", "message, inner"),
            ["System.InvalidOperationError"] = ("global::System.InvalidOperationException", "message, inner"),
            ["System.OverflowError"] = ("global::System.OverflowException", "message, inner"),
            ["System.FormatError"] = ("global::System.FormatException", "message, inner"),
            ["System.IO.IOError"] = ("global::System.IO.IOException", "message, inner"),
            ["System.IO.EndOfStreamError"] = ("global::System.IO.EndOfStreamException", "message, inner"),
            ["System.MissingMemberError"] = ("global::System.MissingMemberException", "message, inner"),
            ["System.InvalidCastError"] = ("global::System.InvalidCastException", "message, inner"),
            ["System.NotSupportedError"] = ("global::System.NotSupportedException", "message, inner"),
        };

        /// <summary>The library's own exception types (those C# gets a class for): the type and the class's full name.</summary>
        private IEnumerable<(PolyglotType Type, string Class)> OwnExceptions() =>
            api.ErrorTypes.Where(name => !Known.ContainsKey(name) && name != "System.Exception")
                .Select(name => model.Types.FirstOrDefault(t => t.Source.FullName == name && t.Source.Arity == 0))
                .OfType<PolyglotType>().Select(type => (type, ExceptionClass(type)));

        /// <summary>The C# exception class of one of the library's exception types (<c>ParseError</c> → <c>ParseException</c>).</summary>
        private static string ExceptionClass(PolyglotType type)
        {
            string name = type.Names[CS];
            string bare = name.EndsWith("Error", StringComparison.Ordinal) ? name[..^5] : name.EndsWith("Exception", StringComparison.Ordinal) ? name[..^9] : name;
            return "global::" + type.Namespaces[CS] + "." + bare + "Exception";
        }

        private string ErrorCases()
        {
            var lines = new List<string>();
            foreach (var name in api.ErrorTypes)
            {
                if (Known.TryGetValue(name, out var known))
                    lines.Add($"                \"{name}\" => new {known.Type}({known.Arguments.Replace("inner", "larva")}),");
            }
            foreach (var (type, @class) in OwnExceptions())
                lines.Add($"                \"{type.Source.FullName}\" => new {@class}(message, type),");
            return string.Join("\n", lines);
        }

        /// <summary>The library's own exceptions as C# exceptions: the same hierarchy (over .NET's for System.Core's bases).</summary>
        private void Exceptions()
        {
            var own = OwnExceptions().ToList();
            foreach (var group in own.GroupBy(o => o.Type.Namespaces[CS]))
            {
                text.Append($"namespace {group.Key}\n{{\n");
                foreach (var (type, @class) in group)
                {
                    var b = type.Source.Base;
                    string @base = b is null || b.FullName == "System.Exception" ? $"global::{root}.LarvaException"
                        : Known.TryGetValue(b.FullName, out var known) ? known.Type
                        : own.FirstOrDefault(o => o.Type.Source == b) is { Class: { } c } ? c : $"global::{root}.LarvaException";
                    string call = @base == $"global::{root}.LarvaException" || own.Any(o => o.Class == @base) ? "message, typeName"
                        : "message, new global::" + root + ".LarvaException(message, typeName)";
                    Doc(type.Source.Doc, "    ");
                    text.Append($"    public class {@class[(@class.LastIndexOf('.') + 1)..]} : {@base}\n    {{\n");
                    text.Append($"        public {@class[(@class.LastIndexOf('.') + 1)..]}(string message, string typeName) : base({call}) {{ }}\n    }}\n\n");
                }
                text.Append("}\n\n");
            }
        }

        private void NativeClass()
        {
            var t = text;
            t.Append($$"""
                namespace {{root}}
                {
                    /// <summary>The library's C functions (each signature blittable: called as it is), and what the face needs of them.</summary>
                    internal static unsafe class LarvaNative
                    {
                        private const string Library = "{{dll}}";


                """);
            foreach (var e in api.Exports)
            {
                t.Append($"        [global::System.Runtime.InteropServices.DllImport(Library, EntryPoint = \"{e.Name}\", ExactSpelling = true)]\n");
                t.Append($"        internal static extern {NativeResult(e)} {e.Name}({string.Join(", ", NativeParameters(e))});\n\n");
            }
            string p = api.Prefix;
            t.Append($$"""
                        /// <summary>Text the library gave (UTF-8), as a string; the library's copy freed.</summary>
                        internal static string? Text(byte* text)
                        {
                            if (text == null)
                                return null;
                            string made = global::System.Runtime.InteropServices.Marshal.PtrToStringUTF8((global::System.IntPtr)text)!;
                            {{p}}_string_free(text);
                            return made;
                        }

                        /// <summary>
                        /// An error the library gave, as an exception (the error's handle given back): what .NET has for
                        /// System.Core's (with a LarvaException inside, its type's name), the face's class for the library's own.
                        /// </summary>
                        internal static global::System.Exception Error(ulong error)
                        {
                            string type = Text({{p}}_error_type(error)) ?? "System.Exception";
                            string message = Text({{p}}_error_message(error)) ?? "";
                            {{p}}_release(error);
                            var larva = new global::{{root}}.LarvaException(message, type);
                            return type switch
                            {
                {{ErrorCases()}}
                                _ => larva,
                            };
                        }

                        private static readonly global::System.Type[] classes =
                        [
                {{string.Join("\n", api.Classes.Select(c => $"                typeof({Full(c)}),"))}}
                        ];

                        /// <summary>
                        /// The object for a handle as the class it is (when it is one C# sees that is a <typeparamref name="T"/>),
                        /// else what <paramref name="fallback"/> makes.
                        /// </summary>
                        internal static T Wrap<T>(ulong handle, global::System.Func<ulong, T> fallback) where T : class
                        {
                            int id = {{p}}_type_of(handle);
                            if (id >= 0 && typeof(T).IsAssignableFrom(classes[id]))
                                return (T)Make(id, handle);
                            return fallback(handle);
                        }

                        private static object Make(int id, ulong handle) => id switch
                        {
                {{string.Join("\n", api.Classes.Select((c, i) => $"                {i} => new {Full(c)}(handle),"))}}
                            _ => throw new global::System.InvalidOperationException(),
                        };

                        /// <summary>
                        /// The C# object an object of the library stands for, when C# made it (an interface C# implements):
                        /// the handle is given back. Null for the library's own objects.
                        /// </summary>
                        internal static object? Foreign(ulong handle)
                        {
                            void* context = {{p}}_foreign_context(handle);
                            if (context == null)
                                return null;
                            {{p}}_release(handle);
                            return global::System.Runtime.InteropServices.GCHandle.FromIntPtr((nint)context).Target;
                        }

                        /// <summary>The handle of an object the library made (0 for null).</summary>
                        internal static ulong Handle(object? value, string name) => value switch
                        {
                            null => 0,
                            global::{{root}}.LarvaObject o => o.__Handle,
                            _ => throw new global::System.ArgumentException("not an object the library made", name),
                        };
                    }

                    /// <summary>An object of the library: its handle, given back when it is disposed (or finalized).</summary>
                    public abstract class LarvaObject : global::System.IDisposable
                    {
                        private ulong handle;

                        internal LarvaObject(ulong handle) => this.handle = handle;

                        /// <summary>The handle (0 once disposed).</summary>
                        internal ulong __Handle => global::System.Threading.Volatile.Read(ref handle);

                        ~LarvaObject() => Release();

                        /// <summary>Gives the handle back (the library's object lives on while the library holds it).</summary>
                        public virtual void Dispose()
                        {
                            Release();
                            global::System.GC.SuppressFinalize(this);
                        }

                        private void Release()
                        {
                            ulong h = global::System.Threading.Interlocked.Exchange(ref handle, 0);
                            if (h != 0)
                                LarvaNative.{{p}}_release(h);
                        }
                    }

                    /// <summary>What the library threw: its message and its type's name in the library (<c>System.Exception</c>).</summary>
                    public class LarvaException : global::System.Exception
                    {
                        public LarvaException(string message, string typeName) : base(message) => TypeName = typeName;

                        /// <summary>The type of what was thrown, as the library names it.</summary>
                        public string TypeName { get; }
                    }
                }


                """);
        }

