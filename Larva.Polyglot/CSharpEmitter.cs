                Call(text, "            ", Op(ExportRole.ListRemoveAt), ["this", "index"], returns: false);
                text.Append("        }\n\n");
                text.Append("        public void Clear()\n        {\n");
                Call(text, "            ", Op(ExportRole.ListClear), ["this"], returns: false);
