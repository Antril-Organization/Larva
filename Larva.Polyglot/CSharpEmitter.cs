using System.Text;
using Larva.Hir;
using Larva.Hir.Services;

namespace Larva.Polyglot
{
    /// <summary>
    /// The C# face of a library built for C (<see cref="ShimGenerator"/>): one source file and a project, in C#'s own terms.
    /// <list type="bullet">
    /// <item>Each class or interface is a class over a handle (<c>LarvaObject</c>: <see cref="IDisposable"/>, with a finalizer
    /// that gives the handle back); an interface is a C# interface, and what the library gives of it a class that
    /// implements it.</item>
    /// <item>A value type is a struct with the same layout (passed by pointer, no copy beyond C#'s own); an enum the same
    /// enum; <c>List&lt;T&gt;</c> a class that is an <see cref="IList{T}"/> over the library's list (no copy).</item>
    /// <item>Text crosses as UTF-8 (a stack buffer for short strings); arrays in as spans (pinned, not copied by C#), out as
    /// arrays; <c>T?</c> as <c>T?</c>.</item>
    /// <item>An error is an exception (<c>LarvaException</c>, with the library's message).</item>
    /// </list>
    /// Calls go straight to the C functions: every signature is blittable (no marshalling).
    /// </summary>
    public sealed class CSharpEmitter
    {
        private readonly PolyglotModel model;
        private readonly CLibrary api;
        private readonly string dll;
        private readonly string root;
        private readonly StringBuilder text = new();
        private readonly Dictionary<PolyglotMember, List<CExport>> byMember = [];
        private readonly Dictionary<string, List<CExport>> byList = new(StringComparer.Ordinal);

        private const TargetLanguage CS = TargetLanguage.CSharp;

        private CSharpEmitter(PolyglotModel model, CLibrary api, string dll)
        {
            this.model = model;
            this.api = api;
            this.dll = dll;
            root = model.Rules(CS).Namespace(model.Assembly.Name);
            foreach (var export in api.Exports)
            {
                if (export.Member is { } member)
                {
                    if (!byMember.TryGetValue(member, out var list))
                        byMember[member] = list = [];
                    list.Add(export);
                }
                if (export.List is { } l)
                {
                    if (!byList.TryGetValue(l.Name, out var list))
                        byList[l.Name] = list = [];
                    list.Add(export);
                }
            }
        }

        /// <summary>The source file (<c>Name.cs</c>) for a library whose native library is <paramref name="dll"/> (without its extension).</summary>
        public static string Write(PolyglotModel model, CLibrary api, string dll, string version)
        {
            var emitter = new CSharpEmitter(model, api, dll);
            emitter.Run(version);
            return emitter.text.ToString();
        }

        /// <summary>A project for the source file: a library with the native library beside it (and in its package).</summary>
        public static string Project(string assembly, string source, string dll, string framework) => $"""
            <Project Sdk="Microsoft.NET.Sdk">

              <!-- Generated by larva polyglot. Do not edit. -->

              <PropertyGroup>
                <TargetFramework>{framework}</TargetFramework>
                <AssemblyName>{assembly}</AssemblyName>
                <RootNamespace>{assembly}</RootNamespace>
                <Nullable>enable</Nullable>
                <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
                <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
                <!-- A generated library: its full assembly only (a reference assembly left in a program's output fails to load). -->
                <ProduceReferenceAssembly>false</ProduceReferenceAssembly>
              </PropertyGroup>

              <ItemGroup>
                <Compile Include="{source}" />
                <!-- The native library and the native libraries it uses: every .dll beside this project, next to the program. -->
                <None Include="*.dll" CopyToOutputDirectory="PreserveNewest" Pack="true" PackagePath="runtimes/win-x64/native" />
              </ItemGroup>

            </Project>

            """;

        // ── Names and types ────────────────────────────────────────

        private string Native => "global::" + root + ".LarvaNative";

        private static string Full(PolyglotType type) =>
            "global::" + (type.Owner is { } owner ? Full(owner)[8..] : type.Namespaces[CS]) + "." + type.Names[CS];

        /// <summary>The class that stands for what the library gives of an interface.</summary>
        private static string Proxy(PolyglotType type) => TargetRules.WithoutI(type.Names[CS]) + "Proxy";

        private static string Keyword(Primitive p) => p switch
        {
            Primitive.Bool => "bool",
            Primitive.I8 => "sbyte",
            Primitive.I16 => "short",
            Primitive.I32 => "int",
            Primitive.I64 => "long",
            Primitive.U8 => "byte",
            Primitive.U16 => "ushort",
            Primitive.U32 => "uint",
            Primitive.U64 => "ulong",
            Primitive.F32 => "float",
            Primitive.F64 => "double",
            _ => "void",
        };

        private static Primitive PrimitiveOf(Cross x) => ((PrimitiveType)(x.Global ?? x.Library)).Kind;

        /// <summary>The C# type of a value that crosses as <paramref name="x"/> (<paramref name="parameter"/>: an argument, arrays as spans).</summary>
        private string Public(Cross x, bool parameter = false) => x.Kind switch
        {
            CrossKind.Number => Keyword(PrimitiveOf(x)),
            CrossKind.Enum or CrossKind.Value => Full(x.Target!),
            CrossKind.Text => x.Nullable ? "string?" : "string",
            CrossKind.Handle => Full(x.Target!) + (x.Nullable ? "?" : ""),
            CrossKind.Array => parameter ? $"global::System.ReadOnlySpan<{Public(x.Element!)}>" : Public(x.Element!) + "[]",
            CrossKind.List => $"global::System.Collections.Generic.IList<{Public(x.Element!)}>",
            CrossKind.Pointer => Pointer(x),
            CrossKind.Optional => Public(x.Element!) + "?",
            CrossKind.Function => Delegate(x.Callback!) + (x.Nullable ? "?" : ""),
            _ => "void",
        };

        /// <summary>The C# delegate type of a callback type (<c>Action&lt;int&gt;</c>, <c>Func&lt;string, bool&gt;</c>).</summary>
        private string Delegate(CCallback callback)
        {
            var arguments = callback.Arguments.Select(a => Public(a)).ToList();
            if (callback.Result.Kind == CrossKind.Void)
                return arguments.Count == 0 ? "global::System.Action" : $"global::System.Action<{string.Join(", ", arguments)}>";
            return $"global::System.Func<{string.Join(", ", [.. arguments, Public(callback.Result)])}>";
        }

        /// <summary>A callback argument's C type in C# (the library to C#): blittable.</summary>
        private IEnumerable<string> CallbackNative(Cross x, string name) => x.Kind switch
        {
            CrossKind.Number => [$"{(PrimitiveOf(x) == Primitive.Bool ? "byte" : Keyword(PrimitiveOf(x)))} {name}"],
            CrossKind.Enum => [$"{Full(x.Target!)} {name}"],
            CrossKind.Text => [$"byte* {name}", $"nuint {name}_length"],
            CrossKind.Value => [$"{Full(x.Target!)}* {name}"],
            _ => [$"ulong {name}"],
        };

        private string CallbackResult(CCallback callback) => callback.Result.Kind switch
        {
            CrossKind.Void => "void",
            CrossKind.Text => "ulong",
            CrossKind.Number => PrimitiveOf(callback.Result) == Primitive.Bool ? "byte" : Keyword(PrimitiveOf(callback.Result)),
            CrossKind.Enum => Full(callback.Result.Target!),
            _ => "ulong",
        };

        /// <summary>The C function type of a callback type in C# (<c>delegate* unmanaged&lt;void*, int, ulong*, void&gt;</c>).</summary>
        private string Pointer(CCallback callback) =>
            "delegate* unmanaged<" + string.Join(", ", ["void*", .. callback.Arguments.SelectMany(a => CallbackNative(a, "x").Select(n => n[..n.LastIndexOf(' ')])), "ulong*", CallbackResult(callback)]) + ">";

        /// <summary>Each callback type's trampoline: what C# gives the library as the C function, and the context's release.</summary>
        /// <summary>
        /// The trampoline of one function another language gives (a callback, or a method of an interface it implements):
        /// <paramref name="target"/> is what it calls on (a delegate, an object), <paramref name="call"/> how.
        /// </summary>
        private void Trampoline(string name, CCallback callback, Func<IReadOnlyList<string>, string> call)
        {
            var parameters = new List<string> { "void* context" };
            var arguments = new List<string>();
            for (int i = 0; i < callback.Arguments.Count; i++)
            {
                var x = callback.Arguments[i];
                string a = "a" + i;
                parameters.AddRange(CallbackNative(x, a));
                arguments.Add(x.Kind switch
                {
                    CrossKind.Number => PrimitiveOf(x) == Primitive.Bool ? $"{a} != 0" : a,
                    CrossKind.Enum => a,
                    CrossKind.Text => $"global::System.Text.Encoding.UTF8.GetString({a}, checked((int){a}_length))",
                    CrossKind.Value => "*" + a,
                    _ => x.Nullable ? $"{a} == 0 ? null : {Wrap(x.Target!).Replace("__r", a)}" : Wrap(x.Target!).Replace("__r", a),
                });
            }
            parameters.Add("ulong* error");
            string result = CallbackResult(callback);
            string invoke = call(arguments);
            string body = callback.Result.Kind switch
            {
                CrossKind.Void => $"{invoke};",
                CrossKind.Number when PrimitiveOf(callback.Result) == Primitive.Bool => $"return {invoke} ? (byte)1 : (byte)0;",
                CrossKind.Number or CrossKind.Enum => $"return {invoke};",
                CrossKind.Text => $"return global::{root}.LarvaCallbacks.Text({invoke});",
                _ => $"return {Native}.Handle({invoke}, \"result\");",
            };
            text.Append("        [global::System.Runtime.InteropServices.UnmanagedCallersOnly]\n");
            text.Append($"        internal static {result} {name}({string.Join(", ", parameters)})\n        {{\n");
            text.Append($"            try\n            {{\n                {body}\n            }}\n");
            text.Append($"            catch (global::System.Exception thrown)\n            {{\n                global::{root}.LarvaCallbacks.Fail(error, thrown);\n");
            if (result != "void")
                text.Append("                return default;\n");
            text.Append("            }\n        }\n\n");
        }

        /// <summary>
        /// Each interface C# can implement: the trampolines of its methods, and Make, the library's object for a C# one
        /// (a handle the caller gives back; the library keeps the C# object alive while it holds it).
        /// </summary>
        private void Foreigns()
        {
            if (api.Foreigns.Count == 0)
                return;
            text.Append($"namespace {root}\n{{\n");
            foreach (var foreign in api.Foreigns)
            {
                string iface = Full(foreign.Interface);
                text.Append($"    internal static unsafe class LarvaForeign{foreign.Index}\n    {{\n");
                for (int m = 0; m < foreign.Methods.Count; m++)
                {
                    var (member, fn) = foreign.Methods[m];
                    string owner = Full(member.Owner);
                    Trampoline("M" + m, fn, arguments =>
                        $"(({owner})global::System.Runtime.InteropServices.GCHandle.FromIntPtr((nint)context).Target!).{member.Names[CS][0]}({string.Join(", ", arguments)})");
                }
                var functions = string.Join(", ", foreign.Methods.Select((_, m) => $"&M{m}"));
                text.Append($$"""
                            /// <summary>The library's object for a C# {{foreign.Interface.Names[CS]}} (a handle the caller gives back).</summary>
                            internal static ulong Make({{iface}} value)
                            {
                                ulong error = 0;
                                ulong handle = LarvaNative.{{foreign.Function}}({{functions}}, global::{{root}}.LarvaCallbacks.Context(value), &global::{{root}}.LarvaCallbacks.Release, &error);
                                if (error != 0)
                                    throw LarvaNative.Error(error);
                                return handle;
                            }
                        }


                    """);
            }
            text.Append("}\n\n");
        }

        private void Callbacks()
        {
            if (api.Callbacks.Count == 0 && api.Foreigns.Count == 0)
                return;
            text.Append($"namespace {root}\n{{\n");
            text.Append($$"""
                    /// <summary>What every callback shares: the context (a GCHandle to the delegate) given back, a failure reported.</summary>
                    internal static unsafe class LarvaCallbacks
                    {
                        [global::System.Runtime.InteropServices.UnmanagedCallersOnly]
                        internal static void Release(void* context) => global::System.Runtime.InteropServices.GCHandle.FromIntPtr((nint)context).Free();

                        /// <summary>What a delegate threw, as the library's caller of the callback will get it (its message).</summary>
                        internal static void Fail(ulong* error, global::System.Exception thrown)
                        {
                            byte[] text = global::System.Text.Encoding.UTF8.GetBytes(thrown.Message);
                            fixed (byte* bytes = text)
                                LarvaNative.{{api.Prefix}}_callback_error(error, bytes, (nuint)text.Length);
                        }

                        /// <summary>Text a callback gives: a string of the library's (it takes the handle).</summary>
                        internal static ulong Text(string value)
                        {
                            byte[] text = global::System.Text.Encoding.UTF8.GetBytes(value);
                            fixed (byte* bytes = text)
                                return LarvaNative.{{api.Prefix}}_string_new(bytes, (nuint)text.Length);
                        }

                        /// <summary>The context of a delegate: a handle that keeps it alive until the library releases it.</summary>
                        internal static void* Context(object function) =>
                            (void*)global::System.Runtime.InteropServices.GCHandle.ToIntPtr(global::System.Runtime.InteropServices.GCHandle.Alloc(function));
                    }


                """);
            foreach (var callback in api.Callbacks)
            {
                text.Append($"    internal static unsafe class LarvaCallback{callback.Index}\n    {{\n");
                Trampoline("Invoke", callback, arguments =>
                    $"(({Delegate(callback)})global::System.Runtime.InteropServices.GCHandle.FromIntPtr((nint)context).Target!)({string.Join(", ", arguments)})");
                text.Append("    }\n\n");
            }
            text.Append("}\n\n");
        }

        /// <summary>A pointer's C# type: to a number or a struct C# sees, typed; anything else (C function pointers too), void*.</summary>
        private static string Pointer(Cross x) => x.Global switch
        {
            PointerType { Target: PrimitiveType p } => (p.Kind == Primitive.Void ? "void" : Keyword(p.Kind)) + "*",
            PointerType when x.Target is { Source.IsValue: true } s => Full(s) + "*",
            _ => "void*",
        };

        /// <summary>The element type of arrays and pointers in native signatures (a C bool is one byte, as C#'s).</summary>
        private string Element(Cross x) => Public(x);

        /// <summary>The class a list type is in C# (<c>StringList</c>).</summary>
        private string ListClass(CList list) => list.Element.Kind switch
        {
            CrossKind.Text => "StringList",
            CrossKind.Number => PrimitiveName(PrimitiveOf(list.Element)) + "List",
            _ => list.Element.Target!.Names[CS] + "List",
        };

        private static string PrimitiveName(Primitive p) => p switch
        {
            Primitive.Bool => "Boolean",
            Primitive.I8 => "SByte",
            Primitive.I16 => "Int16",
            Primitive.I32 => "Int32",
            Primitive.I64 => "Int64",
            Primitive.U8 => "Byte",
            Primitive.U16 => "UInt16",
            Primitive.U32 => "UInt32",
            Primitive.U64 => "UInt64",
            Primitive.F32 => "Single",
            _ => "Double",
        };

        private string ListFull(CList list) => $"global::{root}.{ListClass(list)}";

