using System.Text;

namespace Larva.Polyglot
{
    /// <summary>
    /// The C header of a library (<c>acme_json.h</c>): its handle types, enums, constants and functions, with their
    /// documentation, for C and C++. A value type is a struct with the same fields (in by pointer, out through a pointer
    /// the caller gives); an array goes in as a pointer and a count, and comes out as a block freed with
    /// <c>prefix_free</c> and its count; a list is a handle with functions of its own. A handle is a <c>uint64_t</c> the
    /// library gives and C gives back with
    /// <c>prefix_release</c>; text goes in as a pointer and a length (UTF-8) and comes out as a <c>char *</c> freed with
    /// <c>prefix_string_free</c>; every function takes an error pointer last (it may be null).
    /// </summary>
    public static class CHeader
    {
        public static string Write(CLibrary api, string library, string version)
        {
            string guard = api.Prefix.ToUpperInvariant() + "_H";
            string macro = api.Prefix.ToUpperInvariant() + "_API";
            var text = new StringBuilder();
            text.Append($"/* {library} {version}: generated by larva polyglot. Do not edit. */\n");
            text.Append($"#ifndef {guard}\n#define {guard}\n\n");
            text.Append("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");
            text.Append($"#ifndef {macro}\n#  ifdef _WIN32\n#    define {macro} __declspec(dllimport)\n#  else\n#    define {macro}\n#  endif\n#endif\n\n");
            text.Append("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");

            text.Append($"""
                /*
                 * Every function takes `{api.ErrorType} *error` last. When the call fails, *error is set to an error handle
                 * (its message: {api.Prefix}_error_message; give it back with {api.Prefix}_release) and the result is 0, NULL or false;
                 * when it succeeds, *error is left as it was. Pass NULL to ignore errors.
                 * A thread may call the library at any time; one that will not call it again calls {api.Prefix}_thread_detach.
                 */
                typedef uint64_t {api.ErrorType};


                """);

            foreach (var (name, doc) in api.Handles)
            {
                Doc(text, doc, "");
                text.Append($"typedef uint64_t {name};\n\n");
            }
            foreach (var e in api.Enums)
            {
                Doc(text, e.Doc, "");
                text.Append($"typedef {e.Underlying} {e.Name};\nenum\n{{\n");
                foreach (var (name, value) in e.Members)
                    text.Append($"    {name} = {value},\n");
                text.Append("};\n\n");
            }
            foreach (var s in api.Structs)
            {
                Doc(text, s.Doc, "");
                string tag = s.Name.EndsWith("_t") ? s.Name[..^2] : s.Name;
                if (s.Pack > 0)
                    text.Append($"#pragma pack(push, {s.Pack})\n");
                text.Append($"typedef {(s.Union ? "union" : "struct")} {tag}\n{{\n");
                foreach (var (type, name) in s.Fields)
                    text.Append($"    {(type.EndsWith('*') ? type + name : type + " " + name)};\n");
                if (s.Union && s.Size > 0)
                    text.Append($"    uint8_t size_[{s.Size}];\n");
                text.Append($"}} {s.Name};\n");
                if (s.Pack > 0)
                    text.Append("#pragma pack(pop)\n");
                text.Append('\n');
            }
            if (api.Callbacks.Count > 0 || api.Foreigns.Count > 0)
            {
                text.Append($"""
                    /*
                     * Callbacks: a function the library calls, with the `context` given with it (first), and an error pointer (last).
                     * A callback that fails calls {api.Prefix}_callback_error(error, message, length) and returns: the library's caller
                     * gets that message as an exception. Objects it is given are handles it owns (it gives them back with
                     * {api.Prefix}_release); text it is given lives until it returns. When the library no longer holds the callback it
                     * calls the release given with it (if not NULL) with the context.
                     */
                    typedef void (*{api.ReleaseType})(void *context);


                    """);
            }
            foreach (var callback in api.Callbacks)
                Callback(text, api, callback, null);
            foreach (var foreign in api.Foreigns)
            {
                text.Append($"/* {foreign.Interface.SourceName} implemented outside the library: one function for each method ({foreign.Function}). */\n");
                foreach (var (member, fn) in foreign.Methods)
                    Callback(text, api, fn, member.Display);
            }
            foreach (var c in api.Constants)
            {
                Doc(text, c.Doc, "");
                text.Append($"#define {c.Name} {c.Value}\n");
            }
            if (api.Constants.Count > 0)
                text.Append('\n');
            foreach (var f in api.Exports)
            {
                Doc(text, f.Doc, "", f.Source);
                string parameters = f.Parameters.Count == 0 ? "void" : string.Join(", ", f.Parameters.Select(p => p.Type.EndsWith('*') ? p.Type + p.Name : p.Type + " " + p.Name));
                string result = f.Result.EndsWith('*') ? f.Result : f.Result + " ";
                text.Append($"{macro} {result}{f.Name}({parameters});\n\n");
            }

            text.Append("#ifdef __cplusplus\n}\n#endif\n\n");
            text.Append($"#endif /* {guard} */\n");
            return text.ToString();
        }

        /// <summary>A callback's typedef: text it gives comes back as a handle to a string made with prefix_string_new.</summary>
        private static void Callback(StringBuilder text, CLibrary api, CCallback callback, string? source)
        {
            var parameters = new List<string> { "void *context" };
            for (int i = 0; i < callback.Arguments.Count; i++)
            {
                var x = callback.Arguments[i];
                parameters.Add(x.Kind switch
                {
                    CrossKind.Text => $"const char *a{i}, size_t a{i}_length",
                    CrossKind.Value => $"const {x.C} *a{i}",
                    _ => $"{x.C} a{i}",
                });
            }
            parameters.Add($"{api.ErrorType} *error");
            string result = callback.Result.Kind == CrossKind.Text ? "uint64_t" : callback.Result.C;
            if (source is not null || callback.Result.Kind == CrossKind.Text)
                text.Append($"/* {source}{(source is not null && callback.Result.Kind == CrossKind.Text ? ": " : "")}{(callback.Result.Kind == CrossKind.Text ? $"returns {api.Prefix}_string_new(...)" : "")} */\n");
            text.Append($"typedef {result} (*{callback.Name})({string.Join(", ", parameters)});\n\n");
        }

        private static void Doc(StringBuilder text, string? doc, string indent, string? source = null)
        {
            var lines = new List<string>();
            if (doc is { Length: > 0 })
                lines.AddRange(doc.Split('\n').Select(l => l.TrimEnd().Replace("*/", "* /")));
            if (source is { Length: > 0 })
                lines.Add($"({source})");
            if (lines.Count == 0)
                return;
            text.Append(indent).Append("/*\n");
            foreach (var line in lines)
                text.Append(indent).Append(" * ").Append(line).Append('\n');
            text.Append(indent).Append(" */\n");
        }
    }
}
